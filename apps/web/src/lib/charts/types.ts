/**
 * Типы данных для графиков аналитики
 *
 * Форма хранения — «длинная таблица наблюдений»: одна строка = один факт.
 * Такую форму всегда можно свернуть в любую другую, обратно — нет.
 * Обоснование и разбор форм: docs/analytics-charts/README.md §3
 *
 * Слой данных НЕ знает ничего про типы графиков и оформление.
 */

/** Период в виде `YYYY-MM`. Год обязателен — в исходной таблице его не было, и это давало ошибки. */
export type Period = string

/** Один факт. `series` пусто у показателей с единственным ряд­ом. */
export interface Observation {
  period: Period
  /** Название ряда: регион, банк, категория дохода. */
  series?: string
  /** `null` — данных нет. Отличать от нуля обязательно. */
  value: number | null
  /** Число наблюдений, если известно. Нужно, чтобы не публиковать «100% одобрения» по одной заявке. */
  n?: number
  /** Значение как в источнике, до нормализации единиц. Без него улики ошибок в единицах исчезают. */
  raw?: string
}

/** Единица измерения. Определяет форматирование подписей. */
export type Unit = 'percent' | 'hours' | 'rub' | 'count'

/**
 * Куда «хорошо» для этого показателя.
 *
 * В исходном дизайне цвет означает НЕ направление, а оценку: процент отказа
 * падает — линия зелёная со стрелкой вниз; скорость одобрения растёт — линия
 * серая, потому что одобрять медленнее плохо. Без этого поля цвет соврёт.
 */
export type Polarity = 'higher-is-better' | 'lower-is-better'

/** Форма данных показателя. Определяет, какой пресет графика применим. */
export type IndicatorForm =
  | 'timeseries-single' // один ряд по месяцам
  | 'timeseries-multi' // несколько рядов по месяцам
  | 'distribution' // распределение категорий, сумма ≈100%
  | 'ranking' // рейтинг с меняющимся составом участников
  | 'funnel' // последовательные шаги с потерями
  | 'ordered-relation' // зависимость по упорядоченным интервалам, суммы 100% нет

/** Показатель со всеми наблюдениями. */
export interface Indicator {
  id: string
  title: string
  unit: Unit
  form: IndicatorForm
  /** Куда «хорошо». Определяет цвет динамики, а не направление стрелки. */
  polarity: Polarity
  /** Порядок рядов для легенды и цветов. Если не задан — берётся из данных. */
  series?: string[]
  /**
   * Ряды образуют упорядоченную шкалу (интервалы дохода, размера взноса).
   *
   * Это меняет форму подачи: по упорядоченным интервалам читают ФОРМУ — профиль
   * распределения или зависимость, — а не ищут свою строку. Регионы и программы
   * упорядоченными не являются, там читатель ищет себя.
   * См. chart-guidelines.md §14.
   */
  orderedDomain?: boolean
  /** Откуда данные: вкладка и строки исходной таблицы либо «текст статьи». */
  source?: string
  /** Оговорки к ряду: разрывы методологии, смена знаменателя. Показываются под графиком. */
  notes?: string[]
  observations: Observation[]
}

/** Канал публикации. Диктует размеры и минимальный кегль — см. README §6. */
export type Channel = 'web' | 'email' | 'social'
